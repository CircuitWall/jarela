/**
 * Release-time changeset generation. Diffs the committed surface snapshot
 * (docs/adoption/surface-snapshot.json) against the current one and records
 * the prompt and tool deltas for the release version. Run through
 * `npm run release:changeset`; never imported by the running app.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  changesetFileSchema,
  compareVersions,
  type ChangesetFile,
  type ReleaseChangeset,
} from "./changesets";
import { diffSurfaces, type SurfaceSnapshot } from "./surface-snapshot";

export const ADOPTION_DOCS_DIR = "docs/adoption";
export const CHANGESETS_FILE = `${ADOPTION_DOCS_DIR}/changesets.json`;
export const SNAPSHOT_FILE = `${ADOPTION_DOCS_DIR}/surface-snapshot.json`;
export const CHANGESETS_PAGE = `${ADOPTION_DOCS_DIR}/index.md`;
const MAX_COMMITS = 40;

/** Bullets under `### Adoption` in the version's CHANGELOG section. */
export function extractAdoptionHints(changelog: string, version: string): string[] {
  const lines = changelog.split(/\r?\n/);
  const start = lines.findIndex((line) => new RegExp(`^## \\[?${version.replace(/\./g, "\\.")}\\]?(\\s|$)`).test(line));
  if (start === -1) return [];
  const hints: string[] = [];
  let inAdoption = false;
  for (const line of lines.slice(start + 1)) {
    if (/^## /.test(line)) break;
    if (/^### /.test(line)) {
      inAdoption = /^### Adoption\s*$/i.test(line);
      continue;
    }
    if (!inAdoption) continue;
    const bullet = /^\s*[-*]\s+(.+)$/.exec(line);
    if (bullet) hints.push(bullet[1].trim());
    else if (line.trim() && hints.length > 0) hints[hints.length - 1] += ` ${line.trim()}`;
  }
  return hints;
}

export function buildChangesetEntry(input: {
  version: string;
  previousSnapshot: SurfaceSnapshot;
  nextSnapshot: SurfaceSnapshot;
  date: string;
  hints: string[];
  commits: string[];
}): ReleaseChangeset {
  const delta = diffSurfaces(input.previousSnapshot, input.nextSnapshot);
  return {
    version: input.version,
    previous_version: input.previousSnapshot.version,
    date: input.date,
    hints: input.hints,
    commits: input.commits.slice(0, MAX_COMMITS),
    prompts: delta.prompts,
    tools: delta.tools,
  };
}

export function upsertChangeset(file: ChangesetFile, entry: ReleaseChangeset): ChangesetFile {
  const rest = file.changesets.filter((existing) => existing.version !== entry.version);
  return {
    schema_version: 1,
    changesets: [...rest, entry].sort((a, b) => compareVersions(a.version, b.version)),
  };
}

export function renderChangesetsMarkdown(file: ChangesetFile): string {
  const out = [
    "# Version adoption changesets",
    "",
    "Generated by `npm run release:changeset` — do not edit by hand.",
    "",
    "Each release records how the model-facing surface changed: prompt text Jarela sends and built-in tool",
    "descriptions and parameter schemas. When Jarela starts on a new version, the default agent reads the",
    "changesets between your last adopted version and the running one, then adapts your settings, agent",
    "instructions, skills, and scheduled task or watcher prompts. Code changes are covered by the",
    "[changelog](https://github.com/CircuitWall/jarela/blob/main/CHANGELOG.md).",
    "",
    "Release authors can add adoption hints as bullets under a `### Adoption` heading in the version's",
    "CHANGELOG section.",
  ];
  for (const entry of [...file.changesets].reverse()) {
    out.push("", `## ${entry.version}`, "", `From ${entry.previous_version ?? "—"} · ${entry.date}`, "");
    if (entry.hints.length) {
      out.push("### Adoption hints", "", ...entry.hints.map((hint) => `- ${hint}`), "");
    }
    out.push("### Tools", "");
    if (entry.tools.length === 0) out.push("No tool description or schema changes.");
    for (const tool of entry.tools) {
      const details = [
        tool.description_changed ? "description changed" : "",
        tool.params_added.length ? `params added: ${tool.params_added.map((p) => `\`${p}\``).join(", ")}` : "",
        tool.params_removed.length ? `params removed: ${tool.params_removed.map((p) => `\`${p}\``).join(", ")}` : "",
        tool.params_changed.length ? `params changed: ${tool.params_changed.map((p) => `\`${p}\``).join(", ")}` : "",
        tool.required_added.length ? `now required: ${tool.required_added.map((p) => `\`${p}\``).join(", ")}` : "",
        tool.required_removed.length ? `no longer required: ${tool.required_removed.map((p) => `\`${p}\``).join(", ")}` : "",
      ].filter(Boolean);
      out.push(`- \`${tool.name}\` — ${tool.change}${details.length ? `; ${details.join("; ")}` : ""}`);
    }
    out.push("", "### Prompts", "");
    if (entry.prompts.length === 0) out.push("No prompt text changes.");
    for (const prompt of entry.prompts) {
      out.push(`- \`${prompt.id}\` — ${prompt.change} (\`${prompt.source}\`)`);
      const diff = [
        ...prompt.added_lines.map((line) => `+ ${line}`),
        ...prompt.removed_lines.map((line) => `- ${line}`),
        ...(prompt.omitted_lines > 0 ? [`… ${prompt.omitted_lines} more line(s)`] : []),
      ];
      if (diff.length) out.push("", "    ```diff", ...diff.map((line) => `    ${line}`), "    ```", "");
    }
    if (entry.commits.length) {
      out.push("", "### Commits", "", ...entry.commits.map((subject) => `- ${subject}`));
    }
  }
  return `${out.join("\n").replace(/\n{3,}/g, "\n\n")}\n`;
}

export function readChangesetFile(root: string): ChangesetFile {
  const path = join(root, CHANGESETS_FILE);
  if (!existsSync(path)) return { schema_version: 1, changesets: [] };
  return changesetFileSchema.parse(JSON.parse(readFileSync(path, "utf8")));
}

export function readSnapshot(path: string): SurfaceSnapshot {
  return JSON.parse(readFileSync(path, "utf8")) as SurfaceSnapshot;
}

function snapshotAtTag(root: string, version: string): SurfaceSnapshot | null {
  try {
    const raw = execFileSync("git", ["show", `v${version}:${SNAPSHOT_FILE}`], {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
    });
    return JSON.parse(raw) as SurfaceSnapshot;
  } catch {
    return null;
  }
}

export function gitCommitSubjects(root: string, from: string, to: string): string[] {
  try {
    const raw = execFileSync("git", ["log", "--no-merges", "--format=%s", `${from}..${to}`], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return raw.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
  } catch {
    return [];
  }
}

function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

/**
 * Records the changeset for `version` against the committed snapshot, then
 * moves the committed snapshot forward. Re-running for the same version
 * replaces that entry, diffing against the snapshot committed at the
 * predecessor's release tag.
 */
export function writeReleaseChangeset(input: {
  root: string;
  version: string;
  nextSnapshot: SurfaceSnapshot;
  date: string;
  /** Git ref the release is cut from, for commit subjects. Defaults to HEAD. */
  ref?: string;
  /** Snapshot to diff against instead of the committed one (backfill). */
  previousSnapshot?: SurfaceSnapshot;
}): ReleaseChangeset {
  const snapshotPath = join(input.root, SNAPSHOT_FILE);
  const file = readChangesetFile(input.root);
  let previous = input.previousSnapshot ?? readSnapshot(snapshotPath);
  if (!input.previousSnapshot && previous.version === input.version) {
    const recorded = file.changesets.find((entry) => entry.version === input.version)?.previous_version;
    const prior = recorded ? snapshotAtTag(input.root, recorded) : null;
    if (!prior) {
      throw new Error(`Snapshot is already at ${input.version}; cannot find the v${recorded ?? "?"} snapshot to diff against.`);
    }
    previous = prior;
  }
  if (compareVersions(input.version, previous.version) <= 0) {
    throw new Error(`Release version ${input.version} must be newer than snapshot version ${previous.version}.`);
  }
  const changelogPath = join(input.root, "CHANGELOG.md");
  const changelog = existsSync(changelogPath) ? readFileSync(changelogPath, "utf8") : "";
  const entry = buildChangesetEntry({
    version: input.version,
    previousSnapshot: previous,
    nextSnapshot: { ...input.nextSnapshot, version: input.version },
    date: input.date,
    hints: extractAdoptionHints(changelog, input.version),
    commits: gitCommitSubjects(input.root, `v${previous.version}`, input.ref ?? "HEAD"),
  });
  const updated = upsertChangeset(file, entry);
  writeJson(join(input.root, CHANGESETS_FILE), updated);
  writeFileSync(join(input.root, CHANGESETS_PAGE), renderChangesetsMarkdown(updated), "utf8");
  writeJson(snapshotPath, { ...input.nextSnapshot, version: input.version });
  return entry;
}
